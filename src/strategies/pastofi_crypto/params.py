from __future__ import annotations

from dataclasses import asdict, dataclass


def hms(h: int, m: int, s: int = 0) -> int:
    """시:분:초 → 하루 시작부터의 초 (KST 벽시계)."""
    return h * 3600 + m * 60 + s


@dataclass(frozen=True)
class Params:
    version: str = "pastofi-1.5"
    # 신호
    move_win: int = 300          # 급등락 판정 창(초): mid(T-1) vs mid(T-1-move_win)
    move_bp: float = 200.0       # 급등 ≥ +2%, 급락 ≤ -2% (log 수익률 × 1e4)
    ofi_win: int = 60            # OFI 합산 창(초): (T-61, T-1]
    vol_win: int = 600           # 거래량 창(초): (T-661, T-61] → 분당 평균 = 합 / 10
    ofi_th: float = 0.5          # 로직1: OFI 비율 < -0.5, 로직2: OFI 비율 > +0.5
    guard: int = 1               # 피처 컷오프 T-1초 (T초 데이터는 피처에 안 쓴다)
    fut_limit_bp: float = 950.0  # (1.2) 진입 선물 호가 mid가 기준가 대비 ±9.5% 이상이면 매매 안 함
    fut_min_rem: int = 0         # (1.3: 2, 1.4: 0 = 안 봄) 진입 쪽 선물 1호가 잔량(계약)이 이보다 작으면 매매 안 함
    fut_gap_ticks: int = 2       # (1.3) (선물 호가갭 − 주식 호가갭) ≥ 이 틱 수면 매매 안 함
    skip_chain: int = 60         # (1.3) 필터로 건너뛴 신호가 이 초 안에 다시 나면 같은 신호 → 계속 무시
    vi_pad: int = 60             # 피처 창(T-1-661, T-1] 앞 60초까지 단일가(VI)가 있었으면 판단 안 함
    # 매매
    tp_bp: float = 200.0         # 익절: 진입가 대비 2% 유리한 청산 쪽 선물 호가가 나오면 그 호가로 청산 (1.3)
    sl_bp: float = 200.0         # 손절: 진입가 대비 2% 불리한 청산 쪽 선물 호가가 나오면 그 호가로 청산 (1.3: 1%, 1.5: 2%)
    hold: int = 300              # 최대 보유(초). T+300 이하 마지막 선물 호가로 청산
    cost_bp: float = 1.0         # 선물 왕복 비용 (가정 — 거래세 없음, 수수료는 증권사 조건에 따라 다르다)
    # 시간 (KST, 하루 시작부터의 초)
    session_open: int = hms(9, 0)      # 접속매매 시작 — 피처 창이 이보다 앞이면 판단 안 함
    session_close: int = hms(15, 20)   # 접속매매 끝 — 마감 시각(진입+hold)이 이보다 뒤면 진입 안 함
    entry_start: int = hms(9, 10)      # 판단 시각 T 범위 [entry_start, entry_end)
    entry_end: int = hms(15, 15)

    def to_dict(self) -> dict:
        return asdict(self)


DEFAULT = Params()
VERSION = DEFAULT.version
